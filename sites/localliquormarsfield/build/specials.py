#!/usr/bin/env python3
"""Regenerate the specials block on index.html and the /specials page.

    python3 build/specials.py

Single source of truth is build/specials.json, taken from the Local Liquor
national catalogue. Never hand-edit the generated markup: the next run of this
script will silently revert it. Change the JSON and re-run.

The promo window in the JSON is what check.sh guard 10 reads to refuse a
publish once the specials have expired.
"""
import datetime, json, pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
SITE = HERE.parent
DATA = json.loads((HERE / "specials.json").read_text())

BEGIN = "<!-- BEGIN specials (generated by build/specials.py) -->"
END = "<!-- END specials -->"

# Vessel silhouettes. Filled shapes in the brand's own colour, with the brand
# name squeezed onto the label, read as product; the outline-only cans they
# replaced read as a missing image. Real pack photography would be better still,
# but the catalogue artwork is licensed to the supplier, not to us.
VESSEL = {
    "can": ('<rect x="30" y="18" width="40" height="134" rx="7" fill="{c}"/>'
            '<rect x="30" y="18" width="40" height="10" rx="5" fill="#c3c9d1"/>'
            '<rect x="30" y="152" width="40" height="6" rx="3" fill="#c3c9d1"/>'
            '<rect x="36" y="24" width="7" height="126" rx="3.5" fill="#fff" opacity=".18"/>'),
    "bottle": ('<path d="M41 14h18v26l11 20v88a6 6 0 0 1-6 6H36a6 6 0 0 1-6-6V60l11-20z" fill="{c}"/>'
               '<rect x="40" y="8" width="20" height="10" rx="2" fill="#c3c9d1"/>'
               '<path d="M46 18v22l-9 18v90" stroke="#fff" stroke-opacity=".2" '
               'stroke-width="6" fill="none"/>'),
    "carton": ('<path d="M14 46l36-16 36 16v92l-36 16-36-16z" fill="{c}"/>'
               '<path d="M14 46l36 16 36-16-36-16z" fill="#fff" opacity=".22"/>'
               '<path d="M50 62v92" stroke="#fff" stroke-opacity=".25" stroke-width="2"/>'),
}
LABEL = {"can": (32, 72, 36), "bottle": (30, 78, 40), "carton": (18, 82, 44)}


def ink(hexc):
    """Label text sits on white. Darken pale brand colours until they read."""
    h = hexc.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255
    if lum <= 0.42:
        return hexc
    k = 0.42 / lum
    return "#%02x%02x%02x" % (int(r * k), int(g * k), int(b * k))


def label(it):
    """Brand name on the label, wrapped to two lines and squeezed to fit."""
    x, y, h = LABEL[it["vessel"]]
    w = 100 - 2 * x
    words, lines = it["brand"].split(" "), []
    while words:
        lines.append(words.pop(0))
        while words and len(lines[-1]) + 1 + len(words[0]) <= 11:
            lines[-1] += " " + words.pop(0)
    lines = lines[:2]
    size = 15 if len(lines) == 1 else 13
    top = y + (h - (size * len(lines) + 2 * (len(lines) - 1))) / 2 + size * 0.78
    fill = ink(it["accent"])
    txt = ""
    for i, ln in enumerate(lines):
        txt += ('<text x="50" y="%.1f" text-anchor="middle" fill="%s" font-size="%d" '
                'textLength="%.0f" lengthAdjust="spacingAndGlyphs">%s</text>'
                % (top + i * (size + 2), fill, size,
                   min(w - 6, len(ln) * size * 0.62), ln))
    return ('<rect x="%d" y="%d" width="%d" height="%d" fill="#fff" opacity=".93"/>%s'
            % (x, y, w, h, txt))


def card(it):
    body = (VESSEL[it["vessel"]] + label(it)).format(c=it["accent"])
    alt = re.sub("&[a-z]+;", "&", it["name"] + " " + it["pack"])
    shot = ('<svg viewBox="0 0 100 170" role="img" aria-label="%s">%s</svg>' % (alt, body))
    badge = ""
    if it.get("badge"):
        badge = ('\n    <span class="pack">%s<small>%s</small></span>'
                 % (it["badge"], it["badge_sub"]))
    flag = '\n    <span class="flag">%s</span>' % it["flag"] if it.get("flag") else ""
    if it.get("deal"):
        tag = ('<div class="tag tag-deal"><span class="deal">%s</span>'
               '<span class="amt">$<span>%d</span></span></div>'
               % (it["deal"], it["dollars"]))
    else:
        unit = '<span class="pk">%s</span>' % it["unit"] if it["unit"] else ""
        tag = ('<div class="tag">$<span>%d</span><sup>%s</sup>%s</div>'
               % (it["dollars"], it["cents"], unit))
    return ('\n  <article class="special">%s%s\n    <div class="shot">%s</div>\n'
            '    %s\n    <h3>%s</h3>\n    <p>%s</p>\n  </article>'
            % (badge, flag, shot, tag, it["name"], it["pack"]))


def window():
    f = datetime.date.fromisoformat(DATA["from"])
    t = datetime.date.fromisoformat(DATA["to"])
    fmt = lambda d: d.strftime("%-d %B").replace(" 0", " ")
    return "%s &ndash; %s %s" % (fmt(f), fmt(t), t.strftime("%Y"))


def dates_line():
    ev = ""
    e = DATA.get("event")
    if e and datetime.date.today() <= datetime.date.fromisoformat(e["date"]):
        d = datetime.date.fromisoformat(e["date"])
        ev = (' <strong class="ev">%s is %s</strong> &mdash; we are open until 10pm '
              'Thursday to Saturday.' % (e["name"], d.strftime("%-d %B")))
    return ('<p class="promo-dates">On special <strong>%s</strong> (%s), while stocks '
            'last.%s <span>Catalogue prices for %s. Ring '
            '<a href="tel:+61452480487">0452 480 487</a> to check stock before you '
            'drive over.</span></p>' % (window(), DATA["promo"], ev, DATA["regions"]))


def jumps():
    return ('<nav class="jumps" aria-label="Specials by category">%s</nav>'
            % "".join('<a href="#%s">%s</a>' % (g["id"], g["title"]) for g in DATA["groups"]))


def grid(items):
    return '<div class="specials">%s\n</div>' % "".join(card(i) for i in items)


def home_block():
    feat = [i for g in DATA["groups"] for i in g["items"] if i.get("featured")]
    n = sum(len(g["items"]) for g in DATA["groups"])
    return (BEGIN + "\n<h2>On special <em>now</em></h2>\n" + dates_line() + "\n" + grid(feat)
            + "\n<p class=\"specials-note\">\n  Ten of <strong>%d</strong> lines on promotion "
              "this catalogue.\n  <a href=\"/specials\"><strong>See all %d specials "
              "&rarr;</strong></a>\n  or ring <a href=\"tel:+61452480487\">0452 480 487</a> and "
              "we will put one aside.\n</p>\n" % (n, n)
            + END)


def main():
    idx = (SITE / "index.html").read_text()
    if BEGIN in idx:
        idx = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: home_block(),
                     idx, flags=re.S)
    else:
        old = re.search(r'<h2>In store <em>now</em></h2>.*?</p>\s*(?=<h2>)', idx, re.S)
        if not old:
            raise SystemExit("index.html: found neither the generated markers nor the "
                             "hand-written 'In store now' block to replace")
        idx = idx[:old.start()] + home_block() + "\n\n" + idx[old.end():]
    (SITE / "index.html").write_text(idx)

    # ---- specials.html ----
    import importlib.util
    spec = importlib.util.spec_from_file_location("b", HERE / "build.py")
    b = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(b)

    o = b.head("Specials | Local Liquor Marsfield &mdash; beer, spirits &amp; premix deals",
               "Current Local Liquor specials at Marsfield, 5A 1 Trafalgar Place NSW 2122. "
               "Beer cases, 30-packs and premix deals, %s. Ring 0452 480 487." % window(),
               "/specials", "specials")
    o = o.replace('<main class="wrap">\n',
        '<section class="band">\n  <div class="wrap">\n    <h1>This month&rsquo;s <em>specials</em></h1>\n'
        '    <p class="lede">Every line on promotion at Local Liquor Marsfield, straight from '
        'the current catalogue. Same prices as any Local Liquor store &mdash; without the drive.</p>\n'
        '    <div class="actions">\n'
        '      <a class="btn btn-primary" href="tel:+61452480487">Check stock &mdash; 0452 480 487</a>\n'
        '      <a class="btn btn-secondary" href="https://g.page/r/CenxQG-m-gUkEBI">Get directions</a>\n'
        '    </div>\n  </div>\n</section>\n<main class="wrap">\n')
    o += "\n" + dates_line() + "\n" + jumps() + "\n"
    for g in DATA["groups"]:
        o += ('\n<h2 id="%s">%s</h2>\n<p>%s</p>\n%s\n'
              % (g["id"], g["title"], g["blurb"], grid(g["items"])))
    o += ('\n<h2>Not on the list?</h2>\n<p>\n  The catalogue is only part of the shop. Wine, '
          'single malt, gin and zero-alcohol\n  all sit outside these deals &mdash; '
          '<a href="/spirits">browse the spirits range</a>,\n  '
          '<a href="/range">see the full range</a>, or ring '
          '<a href="tel:+61452480487">0452 480 487</a>\n  and someone will walk the aisle for '
          'you.\n</p>\n'
          '\n<div class="note">\n  <p>\n    Catalogue prices apply %s while stocks last and may '
          'vary in regional\n    areas. We list them here as a guide &mdash; ring the shop to '
          'confirm before\n    making a trip. It is against the law to sell or supply alcohol to, '
          'or to\n    obtain alcohol on behalf of, a person under the age of 18 years.\n  </p>\n'
          '</div>\n' % window())
    (SITE / "specials.html").write_text(o + (SITE / "build" / "footer.html").read_text())

    n = sum(len(g["items"]) for g in DATA["groups"])
    print("specials: %d lines, %d featured on the homepage" % (n, len(
        [i for g in DATA["groups"] for i in g["items"] if i.get("featured")])))
    print("window: %s (%s)" % (window(), DATA["promo"]))
    print("wrote index.html, specials.html")


if __name__ == "__main__":
    main()
